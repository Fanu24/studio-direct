export function tagLabel(slug: string): string {
  if (slug === "non-tech") return "Non-tech";
  if (slug === "cto") return "CTO";
  if (slug === "ai") return "AI";
  if (slug === "nft") return "NFT";
  if (slug === "defi") return "DeFi";
  if (slug === "dao") return "DAO";
  if (slug === "hr") return "HR";
  if (slug === "evm") return "EVM";
  if (slug === "erc") return "ERC";
  if (slug === "pto") return "PTO";
  if (slug === "fsa") return "FSA";
  if (slug === "hsa") return "HSA";
  if (slug === "erc-20") return "ERC-20";
  if (slug === "web3js") return "Web3js";
  if (slug === "web3-py") return "Web3.py";
  return slug
    .split("-")
    .map((word) => word[0]!.toUpperCase() + word.slice(1))
    .join(" ");
}

export function slugifyTag(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function apiTagParam(slug: string): string {
  return slug.replaceAll("-", " ");
}

