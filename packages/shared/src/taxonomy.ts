export type SalaryRole = (typeof SALARY_ROLES)[number];

/**
 * Short salary-page slugs that are still linked and still indexed but are not roles
 * of their own. They are deliberately kept out of SALARY_ROLES: only the canonical
 * long slug may reach the sitemap, the footer and the salary comparison tables, so
 * every salary page keeps exactly one 200 URL. parseSalaryPageSlug folds an alias
 * onto its canonical role, and the page's rel=canonical follows the parsed role, so
 * /web3-salaries/solidity serves the page and points at /web3-salaries/solidity-developer.
 */
export const SALARY_ROLE_ALIASES: Readonly<Record<string, SalaryRole>> = {
  quantitative: "quantitative-developer",
  solidity: "solidity-developer",
};

const salaryRoleAliases = new Map<string, SalaryRole>(
  Object.entries(SALARY_ROLE_ALIASES),
);

/** The canonical SALARY_ROLES member for a slug, resolving aliases; null if neither. */
export function canonicalSalaryRole(slug: string): SalaryRole | null {
  if (isSalaryRole(slug)) return slug;
  return salaryRoleAliases.get(slug) ?? null;
}

